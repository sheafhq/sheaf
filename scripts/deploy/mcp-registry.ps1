<#
.SYNOPSIS
  Publish @sheafhq MCP servers to the official MCP Registry under the
  io.sheafhq/ namespace, proven by HTTP domain verification.
.DESCRIPTION
  -Init     Generate the Ed25519 domain key once. The private seed is
            DPAPI-encrypted to %APPDATA%\sheaf\mcp-registry-key.dpapi and never
            printed; only the public key is shown. The Worker must serve
              https://sheafhq.io/.well-known/mcp-registry-auth
            = "v=MCPv1; k=ed25519; p=<public key>" (src/index.ts).
  -Status   Show whether a key is stored and its public key.
  -Publish  Decrypt the seed in memory, hand it to WSL as MCP_PRIVATE_KEY
            (WSLENV), run `mcp-publisher login http --domain sheafhq.io` and
            `mcp-publisher publish` in -WslDir (must hold server.json).
  -Validate Same as -Publish but runs `mcp-publisher validate` only.
.EXAMPLE
  mcp-registry.ps1 -Init
  mcp-registry.ps1 -Publish -WslDir ~/gate-sheaf/packages/mcp-tools
#>
param(
  [switch]$Init,
  [switch]$Status,
  [switch]$Publish,
  [switch]$Validate,
  [string]$WslDir = '~/gate-sheaf/packages/mcp-tools',
  [string]$Domain = 'sheafhq.io'
)
$ErrorActionPreference = 'Stop'
$dir = Join-Path $env:APPDATA 'sheaf'
$blob = Join-Path $dir 'mcp-registry-key.dpapi'
$pubFile = Join-Path $dir 'mcp-registry-key.pub.txt'

if ($Init) {
  if (Test-Path $blob) { Write-Output "KEY_EXISTS: $blob (delete it first to rotate)"; exit 3 }
  New-Item -ItemType Directory -Force $dir | Out-Null
  # Raw 32-byte Ed25519 seed (hex) + public key (base64), generated by Node in
  # memory and read from stdout straight into a SecureString.
  $js = "const c=require('crypto');const k=c.generateKeyPairSync('ed25519');" +
        "const d=k.privateKey.export({format:'der',type:'pkcs8'});" +
        "const p=k.publicKey.export({format:'der',type:'spki'});" +
        "process.stdout.write(d.subarray(-32).toString('hex')+' '+p.subarray(-32).toString('base64'))"
  $out = (& node -e $js)
  $parts = $out.Split(' ')
  $secure = ConvertTo-SecureString $parts[0] -AsPlainText -Force
  $out = $null; $parts[0] = $null
  ($secure | ConvertFrom-SecureString) | Set-Content -Path $blob -Encoding ascii
  $parts[1] | Set-Content -Path $pubFile -Encoding ascii
  Write-Output "stored (DPAPI): $blob"
  Write-Output "public key: $($parts[1])"
  Write-Output "proof record: v=MCPv1; k=ed25519; p=$($parts[1])"
  exit 0
}

if ($Status) {
  if (-not (Test-Path $blob)) { Write-Output 'NO_KEY: run mcp-registry.ps1 -Init'; exit 5 }
  Write-Output "stored: $blob"
  Write-Output "public key: $((Get-Content $pubFile -Raw).Trim())"
  exit 0
}

if ($Publish -or $Validate) {
  if (-not (Test-Path $blob)) { Write-Output 'NO_KEY: run mcp-registry.ps1 -Init'; exit 5 }
  $secure = (Get-Content $blob -Raw).Trim() | ConvertTo-SecureString
  $bstr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure)
  try {
    $env:MCP_PRIVATE_KEY = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($bstr)
    $env:WSLENV = 'MCP_PRIVATE_KEY'
    $action = if ($Validate) { 'validate' } else { 'publish' }
    # mcp-publisher reads MCP_PRIVATE_KEY from the environment; the key is
    # never on a command line.
    $cmd = "cd $WslDir && ~/.local/bin/mcp-publisher login http --domain $Domain && ~/.local/bin/mcp-publisher $action"
    $out = (& wsl.exe -e bash -lc $cmd 2>&1 | ForEach-Object { $_.ToString() }) -join "`n"
    $code = $LASTEXITCODE
    Write-Output ($out -replace [regex]::Escape($env:MCP_PRIVATE_KEY), '<redacted>')
  }
  finally {
    [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr)
    Remove-Item Env:\MCP_PRIVATE_KEY, Env:\WSLENV -ErrorAction SilentlyContinue
  }
  exit $code
}

Write-Output 'usage: mcp-registry.ps1 -Init | -Status | -Validate | -Publish [-WslDir <dir>]'
exit 2
